// ---------------------------------------------------------------------------
// Answer conditions
// ---------------------------------------------------------------------------

type A = OnboardingAnswers
type Reason = BlockReason<ProcedureId>

const ios = (a: A) => a.apple !== null
const android = (a: A) => a.google !== null
const appleStatusIs = (...statuses: AccountStatus[]) => (a: A) =>
  a.apple !== null && statuses.includes(a.apple.accountStatus)
const googleStatusIs = (...statuses: AccountStatus[]) => (a: A) =>
  a.google !== null && statuses.includes(a.google.accountStatus)
const appleAccessIs = (...models: AppleAccess[]) => (a: A) => a.apple !== null && models.includes(a.apple.access)
const googleAccessIs = (...models: GoogleAccess[]) => (a: A) => a.google !== null && models.includes(a.google.access)

/** Empyrean is expected to get some access (or it's still being decided). */
const appleAccessPlanned = appleAccessIs('admin', 'app-manager', 'undecided')
const googleAccessPlanned = googleAccessIs('account-admin', 'app-admin', 'undecided')

const needs = (field: AnswerField): Reason => ({ kind: 'needs-answer', field })
const pending = (id: StakeholderQuestionId): Reason => ({ kind: 'open-question', id })
const onlyIf = (condition: boolean, reason: Reason): Reason[] => (condition ? [reason] : [])
const reported = (a: A, ...categories: BlockerCategory[]): Reason[] =>
  a.knownBlockers
    .filter((category) => categories.includes(category))
    .map((category): Reason => ({ kind: 'client-blocker', category }))

const appleUndecided = (a: A) => onlyIf(appleAccessIs('undecided')(a), needs('appleAccess'))
const googleUndecided = (a: A) => onlyIf(googleAccessIs('undecided')(a), needs('googleAccess'))

// ---------------------------------------------------------------------------
// Owners that depend on the access model
// ---------------------------------------------------------------------------

/** Who acts inside the client's Apple account. */
const appleActor = (a: A): Owners => {
  switch (a.apple?.access) {
    case 'admin':
    case 'app-manager':
      return ['engineering']
    case 'no-access':
      return ['client']
    default:
      return ['tbc']
  }
}

/** App Manager can't create App Store Connect API keys, so the client creates the keys. */
const appleKeyCreator = (a: A): Owners => {
  switch (a.apple?.access) {
    case 'admin':
      return ['engineering']
    case 'app-manager':
    case 'no-access':
      return ['client']
    default:
      return ['tbc']
  }
}

/** With app-level access the client must create the Play app before inviting Empyrean. */
const playRecordCreator = (a: A): Owners => {
  switch (a.google?.access) {
    case 'account-admin':
      return ['engineering']
    case 'app-admin':
    case 'no-access':
      return ['client']
    default:
      return ['tbc']
  }
}

